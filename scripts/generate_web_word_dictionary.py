#!/usr/bin/env python3
"""Generate the browser's compact index for the pinned CC0 Thai word list.

The generated JavaScript is a build artifact and is intentionally not committed.
It contains word-boundary data only, never IPA or Ukrainian pronunciations.
"""
from __future__ import annotations

import hashlib
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
SOURCE = ROOT / "data" / "thai" / "words_th_cc0.txt"
MANIFEST = ROOT / "data" / "thai" / "word-segmentation-dictionary-source.json"
OUTPUT = ROOT / "web" / "src" / "word-dictionary.generated.js"


def main() -> None:
    raw = SOURCE.read_bytes()
    manifest = json.loads(MANIFEST.read_text(encoding="utf-8"))
    blob_sha1 = hashlib.sha1(
        b"blob " + str(len(raw)).encode("ascii") + b"\0" + raw
    ).hexdigest()
    if blob_sha1 != manifest.get("generated_git_blob_sha1"):
        raise SystemExit(
            "Pinned Thai word-list blob SHA mismatch: "
            f"expected {manifest.get('generated_git_blob_sha1')}, got {blob_sha1}"
        )
    if manifest.get("license") != "CC0-1.0":
        raise SystemExit("Browser word dictionary requires the pinned CC0-1.0 source")
    words = raw.decode("utf-8").splitlines()
    expected = manifest.get("retained_unique_entries")
    if len(words) != expected or len(set(words)) != len(words):
        raise SystemExit(
            f"Thai word-list count/uniqueness mismatch: expected {expected}, got {len(words)}"
        )
    if not all(word and all("\u0e00" <= ch <= "\u0e7f" for ch in word) for word in words):
        raise SystemExit("Thai word list contains an empty or out-of-block entry")
    # Regression guard: this common lexical word contains a supported smaller
    # substring (กา). The browser must prefer the full dictionary word and
    # abstain from a false partial pronunciation.
    if "กาแฟ" not in words:
        raise SystemExit("Pinned word dictionary lacks required boundary regression word กาแฟ")

    buckets: dict[str, list[str]] = {}
    for word in words:
        buckets.setdefault(word[0], []).append(word)
    for candidates in buckets.values():
        candidates.sort(key=lambda word: (-len(word), word))

    serialized = json.dumps(
        list(buckets.items()), ensure_ascii=False, separators=(",", ":")
    )
    output = (
        "// Generated by scripts/generate_web_word_dictionary.py; do not edit.\n"
        f"// Source: {manifest['source_repository']} @ {manifest['source_commit']}\n"
        "// License: CC0-1.0. Segmentation evidence only; no pronunciation data.\n"
        f"export const WORDS_BY_FIRST = new Map({serialized});\n"
    )
    OUTPUT.write_text(output, encoding="utf-8", newline="\n")
    print(
        f"Generated browser Thai word index: {len(words)} words, "
        f"{len(buckets)} initial-character buckets, {len(output.encode('utf-8'))} bytes"
    )


if __name__ == "__main__":
    main()
